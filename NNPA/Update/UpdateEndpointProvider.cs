using System.Text;

namespace NNPA.Update
{
    internal static class UpdateEndpointProvider
    {
        private static readonly byte[] EncodedManifestEndpoint =
        {
            0x32, 0x1F, 0x08, 0xFD, 0xA4, 0x80, 0xEF, 0xA2, 0x94, 0xDD, 0x6A,
            0x7D, 0x04, 0x15, 0xE9, 0xED, 0xC6, 0xD9, 0xBB, 0xB4, 0x8C, 0x8A,
            0x6E, 0x31, 0x5E, 0xE2, 0xFD, 0xCE, 0x9B, 0xB0, 0xA6, 0x83, 0x99,
            0x7D, 0x7F, 0x19, 0x56, 0xE1, 0xF8, 0xCA, 0xD6, 0xB1, 0xCE, 0x84,
            0x66, 0x66, 0x17, 0x1C, 0xE9, 0xF9, 0x86, 0xD3, 0xB9, 0xB4, 0x82
        };

        public static string GetManifestEndpoint()
        {
            byte[] decoded = new byte[EncodedManifestEndpoint.Length];
            for (int index = 0; index < decoded.Length; index++)
            {
                int key = (0x5A + ((index * 17) % 193)) & 0xFF;
                decoded[index] = (byte)(EncodedManifestEndpoint[index] ^ key);
            }

            return Encoding.UTF8.GetString(decoded);
        }
    }
}
